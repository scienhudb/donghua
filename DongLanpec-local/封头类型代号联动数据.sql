-- 1. 创建封头类型代号联动参数表
CREATE TABLE IF NOT EXISTS 封头类型代号联动参数表 (
    主参数名称 VARCHAR(255) NOT NULL COMMENT '主参数名称',
    主参数值 VARCHAR(255) NOT NULL COMMENT '主参数值',
    被联动参数名称 VARCHAR(255) NOT NULL COMMENT '被联动参数名称',
    联动选项 TEXT COMMENT '联动选项（JSON格式或分隔符格式）',
    PRIMARY KEY (主参数名称, 主参数值, 被联动参数名称),
    INDEX idx_主参数名称 (主参数名称),
    INDEX idx_被联动参数名称 (被联动参数名称)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='封头类型代号联动参数表';

